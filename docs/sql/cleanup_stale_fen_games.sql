-- =====================================================================
-- [정리용 / 수동 실행] 폐기된 GameSource.FEN 행 삭제
-- =====================================================================
--
-- 목적:
--   FEN 입력 기능을 PGN 붙여넣기로 교체하면서 GameSource enum 에서 'FEN' 값을 제거했다.
--   로컬/개발 DB에 이전 세션에서 만든 source='FEN' 테스트 행이 남아 있으면,
--   백엔드가 게임 목록을 역직렬화할 때 GameSource.valueOf("FEN") 에서
--   IllegalArgumentException → 500 이 발생한다. 그 잔존 행을 제거한다.
--
-- 실행 전제:
--   - 로컬/개발 DB 한정. 운영 DB에는 source='FEN' 행이 없어야 한다(있다면 점검 후 실행).
--   - 애플리케이션이 만든 테스트 산출물 정리 용도.
--
-- 롤백: 불가(삭제). 실행 전 필요 시 백업.
-- =====================================================================

DELETE FROM games WHERE source = 'FEN';
